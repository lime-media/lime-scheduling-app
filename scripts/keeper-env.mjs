#!/usr/bin/env node
// Pull this deployment's secrets from Keeper Secrets Manager into .env.<env>.
//
// 1. KEEPER_ENV ("uat" | "prod") and KEEPER_KEY (the base64 Keeper device
//    config, see scripts/keeper-init.mjs) come from the process environment
//    (Vercel project env vars) and are saved into the general .env file. When
//    they aren't in the environment (local dev), they're read from .env.
// 2. Every record shared with that Keeper application is fetched. A record's
//    "lime-scheduling-app" custom field names the app env var it fills and its
//    password field holds the value.
// 3. The values, plus DATABASE_URL built from the MSSQL_* parts, are written
//    to .env.<env>, which next.config.mjs compiles into the server bundles.
//
// Runs before `next build` and `next dev` (package.json). On Vercel a Keeper
// failure fails the build; locally an existing .env.<env> is reused with a
// warning so dev works offline.
import path from 'node:path'
import { existsSync } from 'node:fs'
import { getSecrets, loadJsonConfig } from '@keeper-security/secrets-manager-core'
import { readEnvFile, writeEnvFile, upsertEnvFile } from './keeper-envfile.mjs'

const ROOT = process.cwd()
const GENERAL_ENV = path.join(ROOT, '.env')
const ENVS = ['uat', 'prod']
const MAPPING_FIELD = 'lime-scheduling-app'

// Every one of these must come back from Keeper, or the build stops.
export const REQUIRED = [
  'SFDC_CLIENT_ID', 'SFDC_CLIENT_SECRET', 'SFDC_WEBHOOK_SECRET',
  'GOOGLE_SERVICE_ACCOUNT_EMAIL', 'GOOGLE_PRIVATE_KEY',
  'NEXTAUTH_SECRET', 'ANTHROPIC_API_KEY',
  'SMTP_USER', 'SMTP_PASS', 'CRON_SECRET', 'INTERNAL_API_KEY',
  'SAMSARA_API_TOKEN',
  'MSSQL_SERVER', 'MSSQL_USER', 'MSSQL_PASSWORD', 'MSSQL_DATABASE',
]

const onVercel = Boolean(process.env.VERCEL)

function fail(msg) {
  console.error(`[keeper-env] ${msg}`)
  process.exit(1)
}

// Prisma's SQL Server URL: a value containing ; = { } goes inside {braces}, with } doubled.
const sqlPart = (v) => (/[;={}\s]/.test(v) ? `{${v.replace(/}/g, '}}')}}` : v)

export function databaseUrl(v) {
  const port = process.env.MSSQL_PORT || '1433'
  return `sqlserver://${v.MSSQL_SERVER}:${port};database=${sqlPart(v.MSSQL_DATABASE)};user=${sqlPart(v.MSSQL_USER)};password=${sqlPart(v.MSSQL_PASSWORD)};encrypt=true;trustServerCertificate=false`
}

async function main() {
  // Step 1: KEEPER_ENV / KEEPER_KEY from the environment into the general .env.
  const fromProcess = { KEEPER_ENV: process.env.KEEPER_ENV?.trim(), KEEPER_KEY: process.env.KEEPER_KEY?.trim() }
  if (fromProcess.KEEPER_ENV && fromProcess.KEEPER_KEY) upsertEnvFile(GENERAL_ENV, fromProcess)
  const general = readEnvFile(GENERAL_ENV)
  const keeperEnv = (fromProcess.KEEPER_ENV || general.KEEPER_ENV || '').toLowerCase()
  const keeperKey = fromProcess.KEEPER_KEY || general.KEEPER_KEY

  if (!ENVS.includes(keeperEnv)) fail(`KEEPER_ENV must be one of ${ENVS.join(', ')} (got "${keeperEnv}"). Set it in Vercel or in .env.`)
  if (!keeperKey) fail('KEEPER_KEY is not set. Set it in Vercel or in .env (value from .keeper/<env>.json).')

  const outFile = path.join(ROOT, `.env.${keeperEnv}`)

  // Step 2: fetch from Keeper.
  let records
  try {
    ;({ records } = await getSecrets({ storage: loadJsonConfig(keeperKey) }))
  } catch (err) {
    const msg = `Keeper fetch for ${keeperEnv} failed: ${err?.message ?? err}`
    if (!onVercel && existsSync(outFile)) {
      console.warn(`[keeper-env] ${msg}\n[keeper-env] Reusing the existing ${path.basename(outFile)}.`)
      return
    }
    fail(msg)
  }

  const values = {}
  for (const r of records) {
    const target = (r.data.custom ?? []).find((f) => f.label === MAPPING_FIELD)?.value?.[0]
    const envTag = (r.data.custom ?? []).find((f) => f.label === 'environment')?.value?.[0]
    const value = r.data.fields.find((f) => f.type === 'password')?.value?.[0]
    if (!target) continue
    if (envTag && envTag.toLowerCase() !== keeperEnv) {
      fail(`Record "${r.data.title}" is tagged environment=${envTag} but KEEPER_ENV is ${keeperEnv}; check KEEPER_KEY.`)
    }
    if (values[target] !== undefined) fail(`Two Keeper records map to ${target}.`)
    values[target] = value ?? ''
  }

  const missing = REQUIRED.filter((k) => !values[k])
  if (missing.length) fail(`Keeper (${keeperEnv}) is missing or has empty values for: ${missing.join(', ')}`)

  values.DATABASE_URL = databaseUrl(values)

  // Step 3: write the environment-specific file.
  writeEnvFile(outFile, values, [
    `Generated by scripts/keeper-env.mjs from Keeper (${keeperEnv}) at ${new Date().toISOString()}.`,
    'Do not edit or commit; it is rewritten on every build and dev start.',
  ])
  console.log(`[keeper-env] Wrote ${Object.keys(values).length} values for ${keeperEnv} to ${path.basename(outFile)}.`)
}

await main()
