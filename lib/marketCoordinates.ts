export function haversineDistance(lat1: number, lng1: number, lat2: number, lng2: number): number {
  const R = 3958.8 // Earth radius in miles
  const dLat = (lat2 - lat1) * Math.PI / 180
  const dLng = (lng2 - lng1) * Math.PI / 180
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) * Math.sin(dLng / 2) ** 2
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a))
}

function normalizeMarketKey(market: string): string {
  return market.toLowerCase().replace(/\s*,\s*/g, ', ').trim()
}

export function getMarketCoords(market: string): { lat: number; lng: number } | null {
  return COORDS[normalizeMarketKey(market)] ?? null
}

export function getNearbyMarkets(
  selectedMarket: string,
  allMarkets: string[],
  radiusMiles = 250,
): Set<string> {
  const result = new Set<string>()
  result.add(selectedMarket) // always include the selected market itself

  const selectedKey = normalizeMarketKey(selectedMarket)
  const selectedCoords = COORDS[selectedKey]

  if (!selectedCoords) {
    // Unknown market — return only exact match
    return result
  }

  for (const market of allMarkets) {
    if (market === selectedMarket) continue
    const key = normalizeMarketKey(market)
    const coords = COORDS[key]
    if (!coords) continue
    const dist = haversineDistance(selectedCoords.lat, selectedCoords.lng, coords.lat, coords.lng)
    if (dist <= radiusMiles) result.add(market)
  }

  return result
}
